TOTAL_BARS = 128
SPLIT = 60                      # middle C: at or above it is the right hand
KS_FLATS = -2                   # B-flat major

# 8 bars of intro, then seven 16-bar choruses, then an 8-bar tag
SECTIONS = {1: "Intro", 9: "A", 25: "B", 41: "C", 57: "D",
            73: "E", 89: "F", 105: "G", 121: "Tag"}

# B-flat major wants flats, except F-sharp and C-sharp, which turn up as the
# thirds of D7 and A7 rather than as flattened degrees
SPELLING = {0: "C", 1: "D-", 2: "D", 3: "E-", 4: "E", 5: "F",
            6: "F#", 7: "G", 8: "A-", 9: "A", 10: "B-", 11: "B"}


def spell(midi: int) -> pitch.Pitch:
    p = pitch.Pitch(SPELLING[midi % 12])
    p.octave = midi // 12 - 1
    if p.midi != midi:           # B-flat spelled below C rolls the octave
        p.octave += (midi - p.midi) // 12
    return p


def written_offset(slot: int) -> float:
    """Where a slot sits in written time.

    Swing is notated as straight eighths, so the beat is 0.0 and the swung
    "and" - the last triplet of the beat - is 0.5.  Nothing survives on the
    middle triplet, but a note *ending* there rounds to the same eighth.
    """
    beat, part = divmod(slot, 3)
    return beat + (0.0 if part == 0 else 0.5)


# --------------------------------------------------------------------------
# turning strikes into two staves of notes
# --------------------------------------------------------------------------
def hand_events(hand: str) -> list[tuple[float, float, list[int]]]:
    """(start, end, pitches) in written quarter notes from the top of bar 1."""
    out: list[tuple[float, float, list[int]]] = []
    for b, slot, notes in EVENTS:
        keep = [(m, d) for m, d in notes
                if (m >= SPLIT) == (hand == "rh")]
        if not keep:
            continue
        start = 4 * b + written_offset(slot)
        # every note of a strike is held for the longest of them, so the hand
        # reads as one chord rather than a stack of ragged voices
        end = max(4 * b + written_offset(slot + d) for _, d in keep)
        out.append((start, max(end, start + 0.5), [m for m, _ in keep]))
    out.sort()
    # a hand cannot hold one chord into the next, so clip
    for i in range(len(out) - 1):
        s, e, ns = out[i]
        out[i] = (s, min(e, out[i + 1][0]), ns)
    return [(s, e, ns) for s, e, ns in out if e > s]


PIECES = (4.0, 3.0, 2.0, 1.5, 1.0, 0.5)


def split_duration(at: float, length: float) -> list[float]:
    """Break a length into note values an engraver would actually write.

    Nothing crosses the middle of the bar, and a note that starts on an
    upbeat gets no more than a dotted quarter before it ties - which is how a
    swing push is written and keeps the beats visible.
    """
    out: list[float] = []
    pos = round(at * 2) / 2
    left = round(length * 2) / 2
    while left > 1e-9:
        limit = min(left, (pos // 2 + 1) * 2 - pos)
        if pos % 1.0:
            limit = min(limit, 1.5)
        for p in PIECES:
            if p <= limit + 1e-9:
                out.append(p)
                pos = round((pos + p) * 2) / 2
                left = round((left - p) * 2) / 2
                break
        else:                                   # pragma: no cover
            break
    return out


def fill(m: stream.Measure, at: float, length: float, pitches: list[int] | None,
         tie_in: bool, tie_out: bool) -> None:
    """Put a rest or a (possibly tied) chord into a measure."""
    parts = split_duration(at, length)
    for i, ql in enumerate(parts):
        if pitches is None:
            el: note.GeneralNote = note.Rest(quarterLength=ql)
        else:
            el = chord.Chord([spell(p) for p in pitches], quarterLength=ql)
            first, last = i == 0, i == len(parts) - 1
            start = tie_in or not first
            stop = tie_out or not last
            if start and stop:
                el.tie = tie.Tie("continue")
            elif start:
                el.tie = tie.Tie("stop")
            elif stop:
                el.tie = tie.Tie("start")
        m.insert(at, el)
        at += ql


def build_staff(hand: str, clef_obj: clef.Clef) -> stream.PartStaff:
    p = stream.PartStaff()
    p.id = "Piano" + hand.upper()
    p.partName = "Piano" if hand == "rh" else ""
    p.partAbbreviation = "Pno." if hand == "rh" else ""
    p.insert(0, instrument.Piano())
    p.insert(0, clef_obj)
    p.insert(0, meter.TimeSignature("4/4"))
    p.insert(0, key.KeySignature(KS_FLATS))

    events = hand_events(hand)
    idx = 0
    carry: tuple[list[int], float] | None = None      # pitches, absolute end
    for b in range(TOTAL_BARS):
        m = stream.Measure(number=b + 1)
        bar_start, bar_end = 4.0 * b, 4.0 * (b + 1)
        pos = bar_start
        if carry is not None:
            pitches, end = carry
            stop = min(end, bar_end)
            fill(m, 0.0, stop - bar_start, pitches, True, end > bar_end)
            pos = stop
            carry = (pitches, end) if end > bar_end else None
        while idx < len(events) and events[idx][0] < bar_end:
            s, e, pitches = events[idx]
            if s > pos:
                fill(m, pos - bar_start, s - pos, None, False, False)
                pos = s
            stop = min(e, bar_end)
            fill(m, pos - bar_start, stop - pos, pitches, False, e > bar_end)
            pos = stop
            if e > bar_end:
                carry = (pitches, e)
            idx += 1
        if pos < bar_end:
            fill(m, pos - bar_start, bar_end - pos, None, False, False)
        p.append(m)
    return p


def build_score() -> stream.Score:
    sc = stream.Score()
    sc.metadata = metadata.Metadata(
        title="Fly Me To The Moon",
        subtitle="piano, transcribed from the recording",
        composer="Bart Howard",
    )
    rh = build_staff("rh", clef.TrebleClef())
    lh = build_staff("lh", clef.BassClef())

    mm = tempo.MetronomeMark(number=120, referent=note.Note(type="quarter"))
    mm.placement = "above"
    rh.measure(1).insert(0.0, copy.deepcopy(mm))
    swing = expressions.TextExpression("Medium swing - eighths swung")
    swing.placement = "above"
    rh.measure(1).insert(0.0, swing)
    for b, mark in SECTIONS.items():
        meas = rh.measure(b)
        if meas is not None and mark != "Intro":
            meas.insert(0.0, expressions.RehearsalMark(mark))
    for staff in (rh, lh):
        staff[-1].rightBarline = bar.Barline("final")

    sc.insert(0, rh)
    sc.insert(0, lh)
    grp = layout.StaffGroup([rh, lh], name="Piano", abbreviation="Pno.",
                            symbol="brace")
    grp.barTogether = True
    sc.insert(0, grp)
    return sc


def tidy_musicxml(path: str) -> None:
    """Every <voice> must be a positive integer or MuseScore reports the file
    as corrupt."""
    import xml.etree.ElementTree as ET

    tree = ET.parse(path)
    root = tree.getroot()
    for v in root.iter("voice"):
        try:
            if int(v.text) < 1:
                v.text = "1"
        except (TypeError, ValueError):
            v.text = "1"
    tree.write(path, encoding="UTF-8", xml_declaration=True)


def pack_mxl(src: str, dst: str) -> None:
    """Zip the MusicXML into the compressed .mxl MuseScore opens directly."""
    import os
    import zipfile

    inner = os.path.basename(src)
    container = ('<?xml version="1.0" encoding="UTF-8"?>\n'
                 '<container><rootfiles><rootfile full-path="%s" '
                 'media-type="application/vnd.recordare.musicxml+xml"/>'
                 '</rootfiles></container>\n' % inner)
    with zipfile.ZipFile(dst, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("META-INF/container.xml", container)
        z.write(src, inner)


def main() -> None:
    import argparse

    ap = argparse.ArgumentParser(description="write the piano transcription")
    ap.add_argument("-o", "--out", default="Fly_Me_To_The_Moon_Piano.musicxml")
    ap.add_argument("--mxl", help="also write a compressed .mxl here")
    args = ap.parse_args()

    sc = build_score()
    sc.write("musicxml", fp=args.out)
    tidy_musicxml(args.out)
    notes = sum(len(e[2]) for e in EVENTS)
    print(f"wrote {args.out}  ({len(EVENTS)} strikes, {notes} notes)")
    if args.mxl:
        pack_mxl(args.out, args.mxl)
        print(f"wrote {args.mxl}")


if __name__ == "__main__":
    main()
